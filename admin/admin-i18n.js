  let currentLocale = DEFAULT_LOCALE;

  function normalizeLocale(locale) {
    if (locale && LOCALES[locale]) {
      return locale;
    }
    const short = (locale || "").split("-")[0];
    if (LOCALES[short]) {
      return short;
    }
    return DEFAULT_LOCALE;
  }

  function getLocale() {
    return currentLocale;
  }

  function setLocale(locale) {
    currentLocale = normalizeLocale(locale);
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, currentLocale);
    } catch {
      /* ignore */
    }
    return currentLocale;
  }

  function initLocale() {
    try {
      const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
      if (stored) {
        currentLocale = normalizeLocale(stored);
      }
    } catch {
      currentLocale = DEFAULT_LOCALE;
    }
    return currentLocale;
  }

  function ui(key, fallback) {
    const bundle = UI[currentLocale] || UI.en;
    return bundle[key] ?? UI.en[key] ?? fallback ?? key;
  }

  function tabMeta(sectionId) {
    const meta = TAB_META[sectionId];
    if (!meta) {
      return { label: sectionId, what: "", where: "" };
    }
    return meta[currentLocale] || meta.en;
  }

  function sectionDescription(sectionId, englishFallback) {
    const desc = SECTION_DESC[sectionId];
    if (!desc) {
      return englishFallback || "";
    }
    return desc[currentLocale] || desc.en || englishFallback || "";
  }

  window.AdminI18n = {
    LOCALES,
    DEFAULT_LOCALE,
    initLocale,
    getLocale,
    setLocale,
    ui,
    tabMeta,
    sectionDescription,
  };

  initLocale();
