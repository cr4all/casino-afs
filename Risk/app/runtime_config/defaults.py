from app import config as static_config
from app.runtime_config.schema import (
    AmlBlocklistConfig,
    AmlConfig,
    DecisionThresholds,
    FeatureFlags,
    LoggingConfig,
    FingerprintConfig,
    IpIntelConfig,
    OperatorConfig,
    RuntimeConfigData,
    BettingPatternConfig,
    StepUpVerificationConfig,
    StringListConfig,
    WithdrawalMethodConfig,
)
from app.settings import Settings


def _sorted(values: set[str]) -> list[str]:
    return sorted(values)


def build_default_runtime_config(settings: Settings | None = None) -> RuntimeConfigData:
    settings = settings or Settings()

    return RuntimeConfigData(
        decision_thresholds=DecisionThresholds(
            challenge=settings.decision_challenge_threshold,
            high=61,
            block=settings.decision_block_threshold,
        ),
        operator=OperatorConfig(
            platform_name=settings.platform_name,
            licensed_markets=settings.licensed_markets,
        ),
        ip_intel=IpIntelConfig(
            enabled=settings.ip_intel_enabled,
            cache_ttl_seconds=settings.ip_intel_cache_ttl_seconds,
            timeout_seconds=settings.ip_intel_timeout_seconds,
            fail_open=settings.ip_intel_fail_open,
        ),
        aml=AmlConfig(
            single_deposit_threshold=static_config.AML_SINGLE_DEPOSIT_THRESHOLD,
            large_deposit_threshold=static_config.AML_LARGE_DEPOSIT_THRESHOLD,
            withdrawal_review_threshold=static_config.AML_WITHDRAWAL_REVIEW_THRESHOLD,
            structuring_threshold=static_config.AML_STRUCTURING_THRESHOLD,
            micro_deposit_max=static_config.MICRO_DEPOSIT_MAX,
            high_stake_bet_threshold=static_config.HIGH_STAKE_BET_THRESHOLD,
            blocklist=AmlBlocklistConfig(
                enabled=static_config.AML_BLOCKLIST_ENABLED,
                crypto_enabled=static_config.AML_BLOCKLIST_CRYPTO_ENABLED,
                country_enabled=static_config.AML_BLOCKLIST_COUNTRY_ENABLED,
                sync_ofac_crypto_enabled=static_config.AML_BLOCKLIST_SYNC_OFAC_CRYPTO,
                sync_ofac_countries_enabled=static_config.AML_BLOCKLIST_SYNC_OFAC_COUNTRIES,
                sync_interval_hours=static_config.AML_BLOCKLIST_SYNC_INTERVAL_HOURS,
                fail_open=static_config.AML_BLOCKLIST_FAIL_OPEN,
                use_lists_sanctioned_countries=static_config.AML_BLOCKLIST_USE_LISTS_SANCTIONED,
                crypto_hit_score=static_config.AML_BLOCKLIST_CRYPTO_HIT_SCORE,
                country_hit_score=static_config.AML_BLOCKLIST_COUNTRY_HIT_SCORE,
            ),
        ),
        fingerprint=FingerprintConfig(
            required_channels=_sorted(static_config.FINGERPRINT_REQUIRED_CHANNELS),
            min_length=static_config.FINGERPRINT_MIN_LENGTH,
            max_length=static_config.FINGERPRINT_MAX_LENGTH,
            suspicious_values=_sorted(static_config.SUSPICIOUS_FINGERPRINT_VALUES),
        ),
        lists=StringListConfig(
            disposable_domains=_sorted(static_config.DISPOSABLE_DOMAINS),
            generic_names=_sorted(static_config.GENERIC_NAMES),
            role_based_email_locals=_sorted(static_config.ROLE_BASED_EMAIL_LOCALS),
            suspicious_email_tlds=_sorted(static_config.SUSPICIOUS_EMAIL_TLDS),
            suspicious_email_local_tokens=_sorted(static_config.SUSPICIOUS_EMAIL_LOCAL_TOKENS),
            high_risk_countries=_sorted(static_config.HIGH_RISK_COUNTRIES),
            sanctioned_countries=_sorted(static_config.SANCTIONED_COUNTRIES),
            bot_user_agent_tokens=_sorted(static_config.BOT_USER_AGENT_TOKENS),
            emulator_ua_tokens=_sorted(static_config.EMULATOR_UA_TOKENS),
            suspicious_referrers=_sorted(static_config.SUSPICIOUS_REFERRERS),
            bonus_abuse_referrer_tokens=_sorted(static_config.BONUS_ABUSE_REFERRER_TOKENS),
        ),
        velocity_thresholds=dict(static_config.VELOCITY_THRESHOLDS),
        score_weights=dict(static_config.SCORE_WEIGHTS),
        withdrawal_method=WithdrawalMethodConfig(
            enabled=static_config.WITHDRAWAL_METHOD_ENABLED,
            distinct_users_medium=static_config.WITHDRAWAL_METHOD_DISTINCT_USERS_MEDIUM,
            distinct_users_high=static_config.WITHDRAWAL_METHOD_DISTINCT_USERS_HIGH,
            distinct_users_critical=static_config.WITHDRAWAL_METHOD_DISTINCT_USERS_CRITICAL,
            medium_score=static_config.WITHDRAWAL_METHOD_MEDIUM_SCORE,
            high_score=static_config.WITHDRAWAL_METHOD_HIGH_SCORE,
            critical_score=static_config.WITHDRAWAL_METHOD_CRITICAL_SCORE,
        ),
        betting_patterns=BettingPatternConfig(
            enabled=static_config.BETTING_PATTERNS_ENABLED,
            burst_window_seconds=static_config.BETTING_BURST_WINDOW_SECONDS,
            game_bet_burst_medium=static_config.GAME_BET_BURST_MEDIUM,
            game_bet_burst_high=static_config.GAME_BET_BURST_HIGH,
            game_bet_burst_critical=static_config.GAME_BET_BURST_CRITICAL,
            game_bet_medium_score=static_config.GAME_BET_MEDIUM_SCORE,
            game_bet_high_score=static_config.GAME_BET_HIGH_SCORE,
            game_bet_critical_score=static_config.GAME_BET_CRITICAL_SCORE,
            wallet_bet_burst_medium=static_config.WALLET_BET_BURST_MEDIUM,
            wallet_bet_burst_high=static_config.WALLET_BET_BURST_HIGH,
            wallet_bet_burst_critical=static_config.WALLET_BET_BURST_CRITICAL,
            wallet_bet_medium_score=static_config.WALLET_BET_MEDIUM_SCORE,
            wallet_bet_high_score=static_config.WALLET_BET_HIGH_SCORE,
            wallet_bet_critical_score=static_config.WALLET_BET_CRITICAL_SCORE,
            wallet_win_burst_medium=static_config.WALLET_WIN_BURST_MEDIUM,
            wallet_win_burst_high=static_config.WALLET_WIN_BURST_HIGH,
            wallet_win_burst_critical=static_config.WALLET_WIN_BURST_CRITICAL,
            wallet_win_medium_score=static_config.WALLET_WIN_MEDIUM_SCORE,
            wallet_win_high_score=static_config.WALLET_WIN_HIGH_SCORE,
            wallet_win_critical_score=static_config.WALLET_WIN_CRITICAL_SCORE,
            win_rate_min_bets=static_config.WIN_RATE_MIN_BETS,
            win_rate_high_ratio=static_config.WIN_RATE_HIGH_RATIO,
            win_rate_critical_ratio=static_config.WIN_RATE_CRITICAL_RATIO,
            win_rate_high_score=static_config.WIN_RATE_HIGH_SCORE,
            win_rate_critical_score=static_config.WIN_RATE_CRITICAL_SCORE,
        ),
        step_up_verification=StepUpVerificationConfig(
            enabled=static_config.STEP_UP_VERIFICATION_ENABLED,
            grant_ttl_days=static_config.STEP_UP_VERIFICATION_GRANT_TTL_DAYS,
            max_verified_age_minutes=static_config.STEP_UP_VERIFICATION_MAX_VERIFIED_AGE_MINUTES,
            downgrade_challenge_to_allow=static_config.STEP_UP_VERIFICATION_DOWNGRADE_CHALLENGE,
            applicable_event_types=list(static_config.STEP_UP_VERIFICATION_EVENT_TYPES),
        ),
        critical_signals=sorted(
            {
                "bulk_login_attack",
                "bulk_signup_attack",
                "credential_stuffing_suspected",
                "bot_user_agent",
                "automated_login_attempt",
                "disposable_email",
                "multi_account_fingerprint_abuse",
                "multi_account_shared_withdrawal_method",
                "ofac_sanctioned_wallet",
                "blocklisted_payout_address",
                "blocklisted_country",
                "sanctioned_country",
                "vpn_withdrawal_attempt",
                "emulator_detected",
                "brute_force_login_suspected",
                "new_device_on_withdrawal",
            }
        ),
        features=FeatureFlags(
            sync_publish_audit=settings.sync_publish_audit,
            decision_cache_ttl_seconds=settings.decision_cache_ttl_seconds,
            redis_enabled=settings.redis_enabled,
            redis_velocity_ip_ttl=settings.redis_velocity_ip_ttl,
            redis_velocity_domain_ttl=settings.redis_velocity_domain_ttl,
            rabbitmq_enabled=settings.rabbitmq_enabled,
            rabbitmq_publish_results=settings.rabbitmq_publish_results,
            rabbitmq_events_exchange=settings.rabbitmq_events_exchange,
            rabbitmq_events_exchange_type=settings.rabbitmq_events_exchange_type,
            rabbitmq_events_queue=settings.rabbitmq_events_queue,
            rabbitmq_events_binding_key=settings.rabbitmq_events_binding_key,
            rabbitmq_prefetch=settings.rabbitmq_prefetch,
            rabbitmq_results_queue=settings.rabbitmq_results_queue,
        ),
        logging=LoggingConfig(
            sync_enabled=settings.evaluate_file_log_enabled,
            async_enabled=settings.evaluate_file_log_enabled,
        ),
    )
